"""design.from_prompt: text description -> HTML/CSS (+ inline SVG icons), rendered and screenshotted.

Engines:
  spec   (default) deterministic parser -> layout spec -> accessible HTML (palette verified for contrast)
  lm     the local XON LM generates HTML from '<|task|>description<|html|>' (weak at Tier A; measured)
  remote any configured chat backend (agent.backends), when an API key is present
"""
from __future__ import annotations

import random
import re

from xon.datasets.synth_ui import FONTS, ICON_PATHS, spec_to_html
from xon.design import brand, palette

COLOR_WORDS = {"blue": "#2f5fd0", "red": "#c62828", "green": "#2e7d32", "purple": "#6a3fc1", "orange": "#e0660f",
               "teal": "#00838f", "pink": "#c2185b", "yellow": "#b38f00", "gray": "#546e7a", "grey": "#546e7a",
               "black": "#222222", "indigo": "#3949ab", "brown": "#795548"}
FIELD_WORDS = ["name", "email", "password", "city", "phone", "company", "message", "search", "title", "date", "address"]


class Refused(ValueError):
    pass


def parse(prompt: str, seed: int = 0) -> dict:
    p = prompt.lower()
    rng = random.Random(seed)
    m = re.search(r"#[0-9a-f]{6}\b", p)
    base = m.group(0) if m else next((v for k, v in COLOR_WORDS.items() if re.search(rf"\b{k}\b", p)), "#2f5fd0")
    dark = bool(re.search(r"\bdark\b|\bnight\b", p))
    pal = palette.generate(base, dark=dark)["tokens"]
    spec_pal = {"bg": pal["bg"], "surface": pal["surface"], "primary": pal["primary"], "accent": pal["accent"],
                "text": pal["text"], "muted": pal["muted"], "dark": dark}
    font = FONTS[2] if "mono" in p or "code" in p else FONTS[1] if "serif" in p and "sans" not in p else FONTS[0]
    radius = 0 if re.search(r"\bsharp|square|brutal", p) else 16 if re.search(r"\bround|soft|friendly", p) else 8
    title = re.search(r"(?:called|named|titled|for)\s+['\"]?([A-Z][\w ]{1,30}?)['\"]?(?:[,.]| with| that|$)", prompt)
    brand_name = title.group(1).strip() if title else "Studio"
    secs: list[dict] = []

    def num(word: str, default: int) -> int:
        mm = re.search(rf"(\d+|two|three|four|five|six)\s+{word}", p)
        if not mm:
            return default
        w = mm.group(1)
        return int(w) if w.isdigit() else ["two", "three", "four", "five", "six"].index(w) + 2

    if re.search(r"\bnav|menu|header|navigation", p) or True:
        links = re.findall(r"links? (?:to |for )?([a-z ,]+?)(?:\.|;| and a| with|$)", p)
        names = [w.strip().capitalize() for w in re.split(r",| and ", links[0])][:5] if links else ["Home", "Features", "Pricing", "About"]
        secs.append({"kind": "nav", "brand": brand_name, "links": [n for n in names if n], "icon": "star"})
    if re.search(r"\bhero|landing|headline|banner|welcome", p) or not re.search(r"card|form|table|modal|list", p):
        head = re.search(r"(?:headline|heading|tagline)\s+['\"]([^'\"]+)['\"]", prompt)
        secs.append({"kind": "hero", "title": head.group(1) if head else f"Welcome to {brand_name}",
                     "subtitle": "A simple, accessible page generated by XON from your description.",
                     "buttons": ["Get started", "Learn more"] if "two button" in p or "buttons" in p else ["Get started"],
                     "align": "center" if "center" in p else "left"})
    if re.search(r"card|feature|pricing|plan|product|grid", p):
        n = num("cards?", num("features?", num("plans?", 3)))
        kind_title = "Plan" if "pricing" in p or "plan" in p else "Feature"
        icons = list(ICON_PATHS)
        secs.append({"kind": "cards", "cols": min(n, 4), "items": [
            {"title": f"{kind_title} {i + 1}", "text": "Short description of this item.", "icon": icons[i % len(icons)],
             "button": "Choose" if kind_title == "Plan" else None} for i in range(n)]})
    if re.search(r"form|sign ?up|contact|subscribe|newsletter|input|field", p):
        fields = [f.capitalize() for f in FIELD_WORDS if re.search(rf"\b{f}\b", p)] or ["Name", "Email"]
        secs.append({"kind": "form", "title": "Contact us" if "contact" in p else "Sign up", "fields": fields[:4],
                     "button": "Subscribe" if "subscribe" in p or "newsletter" in p else "Submit"})
    if re.search(r"table|list of|data|report|dashboard", p):
        secs.append({"kind": "table", "head": ["Item", "Status", "Value"],
                     "rows": [[f"Row {i + 1}", rng.choice(["Active", "Paused", "Done"]), str(rng.randint(10, 999))] for i in range(3)]})
    if re.search(r"modal|dialog|popup", p):
        secs.append({"kind": "modal", "title": "Confirm", "text": "Are you sure you want to continue?", "button": "Confirm"})
    return {"palette": spec_pal, "font": font, "radius": radius, "space": 12, "sections": secs, "prompt": prompt}


def generate(prompt: str, engine: str = "spec", seed: int = 0, lm=None, tok=None, backend=None) -> dict:
    why = brand.check(prompt)
    if why:
        raise Refused(why)
    if engine == "lm" and lm is not None:
        from xon.lm.generate import complete
        html = complete(lm, tok, f"<|task|>{prompt}<|html|>", max_new=400, temperature=0.7, seed=seed)
        return {"engine": "lm", "html": html, "spec": None}
    if engine == "remote" and backend is not None:
        msg = backend.chat([{"role": "user", "content": "Write one self-contained accessible HTML page (inline CSS, "
                             f"no external assets) for: {prompt}\nReturn only the HTML."}])
        html = re.sub(r"^```\w*\n|```$", "", msg.strip())
        return {"engine": "remote", "html": html, "spec": None}
    spec = parse(prompt, seed)
    return {"engine": "spec", "html": spec_to_html(spec), "spec": spec}


def render(result: dict, out_png=None, renderer=None):
    from xon.design.render import Renderer
    own = renderer is None
    r = renderer or Renderer(640, 480).__enter__()
    try:
        img = r.screenshot_html(result["html"], 640, 480)
    finally:
        if own:
            r.__exit__(None, None, None)
    if out_png:
        img.save(out_png)
    return img
