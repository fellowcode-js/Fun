"""Code cleaning: license gate, secret scrub, minified/generated filters, exact + MinHash near-dedupe."""
from __future__ import annotations

import ast
import hashlib
import random
import re

from xon.crawler.extract import PERMISSIVE
from xon.pipeline.clean_text import PII_PATTERNS, unsafe_reason

GENERATED = re.compile(r"(?i)(auto-?generated|do not edit|generated by|@generated)")


def norm_hash(code: str) -> str:
    """Hash with whitespace and comments-light normalization (exact-dup detection)."""
    t = re.sub(r"\s+", " ", code).strip()
    return hashlib.sha1(t.encode()).hexdigest()


def scrub_secrets(code: str) -> tuple[str, int]:
    n = 0
    for tag, pat in PII_PATTERNS:
        if tag not in ("SECRET", "EMAIL"):
            continue  # phone/address regexes misfire on numeric code
        def repl(m, tag=tag):
            nonlocal n
            n += 1
            if tag == "SECRET" and m.lastindex and m.lastindex >= 3:
                return f"{m.group(1)}{m.group(2)}{m.group(3)}<SECRET>{m.group(3)}"
            return f"<{tag}>"
        code = pat.sub(repl, code)
    return code, n


def reject_reason(code: str, lang: str, license: str | None) -> str | None:
    if license not in PERMISSIVE:
        return f"license:{license or 'unknown'}"
    if len(code) < 40:
        return "too_short"
    if len(code) > 400_000:
        return "too_long"
    lines = code.splitlines() or [""]
    if max(len(l) for l in lines) > 1000 or sum(map(len, lines)) / len(lines) > 200:
        return "minified"
    if GENERATED.search(code[:2000]):
        return "generated"
    if unsafe_reason(code):
        return "unsafe"
    return None


def python_ok(code: str) -> bool:
    try:
        ast.parse(code)
        return True
    except (SyntaxError, ValueError):
        return False


class MinHashDeduper:
    """Near-duplicate detection: MinHash over token 5-shingles + LSH banding."""

    def __init__(self, num_perm: int = 64, bands: int = 16, threshold: float = 0.8, seed: int = 7):
        self.num_perm, self.bands, self.rows = num_perm, bands, num_perm // bands
        self.threshold = threshold
        rng = random.Random(seed)
        self.p = (1 << 61) - 1
        self.a = [rng.randrange(1, self.p) for _ in range(num_perm)]
        self.b = [rng.randrange(0, self.p) for _ in range(num_perm)]
        self.buckets: dict[tuple, list[int]] = {}
        self.sigs: list[list[int]] = []

    def signature(self, text: str) -> list[int]:
        toks = re.findall(r"\w+|[^\w\s]", text)
        sh = {hash(" ".join(toks[i:i + 5])) & 0xFFFFFFFF for i in range(max(1, len(toks) - 4))}
        return [min(((a * h + b) % self.p) for h in sh) for a, b in zip(self.a, self.b)]

    @staticmethod
    def jaccard(s1, s2) -> float:
        return sum(x == y for x, y in zip(s1, s2)) / len(s1)

    def add(self, text: str) -> bool:
        """Returns True if text is new (and records it); False if a near-duplicate exists."""
        sig = self.signature(text)
        cands = set()
        keys = []
        for bi in range(self.bands):
            k = (bi, tuple(sig[bi * self.rows:(bi + 1) * self.rows]))
            keys.append(k)
            cands.update(self.buckets.get(k, ()))
        for c in cands:
            if self.jaccard(sig, self.sigs[c]) >= self.threshold:
                return False
        idx = len(self.sigs)
        self.sigs.append(sig)
        for k in keys:
            self.buckets.setdefault(k, []).append(idx)
        return True
